"""Compare compiled scalar Lane B code with independently generated HF NPZs.

Usage: python lane_b_fixture_test.py FIXTURE_DIR [--build-dir PATH]
The fixtures are generated by a separate owner from pinned HF 09281b8.
"""
import argparse
import ctypes as C
from pathlib import Path
import subprocess
import tempfile
import sys
try:
    import numpy as np
except ImportError:
    print('SKIP: numpy is required for independent NPZ fixture checks')
    sys.exit(77)

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('fixtures', type=Path)
parser.add_argument('--build-dir', type=Path)
parser.add_argument('--library', type=Path)
args = parser.parse_args()
for fixture in ['router_sigmoid.npz', 'swiglu_clamped.npz', 'indexer_kpool.npz', 'mla_attention.npz']:
    if not (args.fixtures / fixture).is_file():
        print(f'SKIP: missing external fixture {args.fixtures / fixture}')
        sys.exit(77)
root = Path(__file__).resolve().parents[3]
if args.library:
    libpath = args.library.resolve()
else:
    output = args.build_dir or Path(tempfile.mkdtemp(prefix='glm53-lane-b-'))
    output.mkdir(parents=True, exist_ok=True)
    libpath = output / 'lane_b_reference.so'
    subprocess.run(['c++', '-std=c++20', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', '-fPIC', '-I', str(root),
                    str(root / 'src/models/glm53_flash/reference_moe.cpp'),
                    str(root / 'src/models/glm53_flash/reference_mla.cpp'),
                    str(Path(__file__).with_name('lane_b_bridge.cpp')),
                    '-o', str(libpath)], check=True)
lib = C.CDLL(str(libpath))
P = C.c_void_p
lib.glm_route.argtypes = [P, P, C.c_int, C.c_int, C.c_int, P, P]
lib.glm_dense.argtypes = [P, P, P, P, C.c_int, C.c_int, P]
lib.glm_swiglu.argtypes = [P, C.c_int, P]
lib.glm_routed.argtypes = [P, P, P, C.c_int, C.c_int, P, P, C.c_int, P]
for name in ['glm_route', 'glm_dense', 'glm_swiglu', 'glm_routed']:
    getattr(lib, name).restype = None

def ptr(a):
    assert a.flags.c_contiguous
    assert a.dtype in (np.dtype('float32'), np.dtype('int32'))
    return a.ctypes.data

def check(name, actual, expected):
    assert np.isfinite(actual).all(), name
    diff = np.linalg.norm(actual.astype('float64') - expected)
    rel = diff / max(np.linalg.norm(expected.astype('float64')), 1e-30)
    assert rel <= 1e-5, (name, rel)
    print(f'{name}: rel_l2={rel:.3g} PASS')

z = np.load(args.fixtures / 'router_sigmoid.npz')
bias = z['w.e_score_correction_bias']
for case, used in [('main', 2), ('edge_top2', 2), ('edge_top8', 8)]:
    for hf, variant in [(0, 'llama'), (1, 'hf')]:
        expected_ids = z[f'{case}.topk_indices_by_id']
        expected_w = z[f'{case}.topk_weights_{variant}_by_id']
        got = np.empty_like(expected_w)
        for t, logits in enumerate(z[f'{case}.router_logits']):
            ids = np.empty(used, dtype='int32')
            weights = np.empty(used, dtype='float32')
            lib.glm_route(ptr(logits), ptr(bias), logits.size, used, hf,
                          ptr(ids), ptr(weights))
            order = np.argsort(ids)
            assert np.array_equal(ids[order], expected_ids[t]), (case, ids)
            got[t] = weights[order]
        check(f'router/{case}/{variant}', got, expected_w)
z = np.load(args.fixtures / 'swiglu_clamped.npz')
for case in ['dense', 'shared']:
    x, expected = z[f'{case}.x'], z[f'{case}.y']
    gate, up, down = (z[f'{case}.w.{k}_proj'] for k in ['gate', 'up', 'down'])
    y = np.empty_like(expected)
    for a, b in zip(x.reshape(-1, x.shape[-1]), y.reshape(-1, y.shape[-1])):
        lib.glm_dense(ptr(a), ptr(gate), ptr(up), ptr(down), a.size,
                      gate.shape[0], ptr(b))
    check(case, y, expected)
gu = z['routed.gate_up']
y = np.empty_like(z['routed.act'])
for a, b in zip(gu, y):
    lib.glm_swiglu(ptr(a), b.size, ptr(b))
check('routed/swiglu', y, z['routed.act'])
x = z['moe.x'].reshape(-1, 32)
y = np.empty_like(x)
expert_gu = z['w.experts.gate_up_proj']
expert_down = z['w.experts.down_proj']
for t, a in enumerate(x):
    ids = z['moe.topk_indices'][t].astype('int32')
    w = z['moe.topk_weights'][t]
    lib.glm_routed(ptr(a), ptr(expert_gu),
                   ptr(expert_down), 32, 16, ptr(ids), ptr(w),
                   len(ids), ptr(y[t]))
y += z['moe.shared_y'].reshape(y.shape)
check('moe/routed+shared', y, z['moe.y'].reshape(y.shape))

lib.glm_norm.argtypes = [P, P, P, C.c_int, P]
lib.glm_pool.argtypes = [P, P, P, C.c_int, C.c_int, P]
lib.glm_scores.argtypes = [P, P, P, C.c_int, C.c_int, C.c_int, P]
lib.glm_select.argtypes = [P, C.c_int, C.c_int, C.c_int, C.c_int, C.c_int, P]
lib.glm_select.restype = C.c_int
for name in ['glm_norm', 'glm_pool', 'glm_scores']:
    getattr(lib, name).restype = None
z = np.load(args.fixtures / 'indexer_kpool.npz')
k, gate, ape = z['k_raw'], z['gate_scores'], z['w.compress_ape']
w, bias = z['w.k_norm.weight'], z['w.k_norm.bias']
ln = np.empty_like(k)
for b in range(k.shape[0]):
    for t in range(k.shape[1]):
        lib.glm_norm(ptr(k[b, t]), ptr(w), ptr(bias), k.shape[-1], ptr(ln[b, t]))
check('indexer/layernorm', ln, z['k_layernorm'])
pools = np.zeros_like(z['pool_keys'])
for b, first in [(0, 0), (1, 3)]:
    count = (k.shape[1] - first) // 4
    for p in range(count):
        t = first + p * 4
        lib.glm_pool(ptr(ln[b, t:t+4]), ptr(gate[b, t:t+4]), ptr(ape),
                     4, k.shape[-1], ptr(pools[b, p]))
    check(f'indexer/pools/batch{b}', pools[b, :count], z['pool_keys'][b, :count])
    x = z['x'][b]
    projection = z['w.weights_proj']
    raw_w = np.ascontiguousarray(x @ projection.T)
    iq = z['iq'][b]
    scores = np.zeros((x.shape[0], count), dtype='float32')
    for t in range(x.shape[0]):
        lib.glm_scores(ptr(iq[t]), ptr(pools[b, :count]), ptr(raw_w[t]),
                       iq.shape[1], iq.shape[2], count, ptr(scores[t]))
    check(f'indexer/scores/batch{b}', scores, z['index_scores'][b, :, :count])
    for tail, key in [(1, 'topk_indices'), (0, 'topk_indices_no_tail')]:
        for t in range(x.shape[0]):
            ids = np.full(11, -1, dtype='int32')
            n = lib.glm_select(ptr(scores[t]), t+1, first, 4, 2, tail, ptr(ids))
            expected = z[key][b, t]
            expected = expected[expected >= 0]
            assert np.array_equal(np.sort(ids[:n]), np.sort(expected)), (b, t, tail, ids[:n], expected)
        print(f'indexer/selection/batch{b}/tail{tail}: exact sets PASS')

lib.glm_absorb.argtypes = [P, P, C.c_int, C.c_int, C.c_int, P]
lib.glm_attention.argtypes = [P, P, C.c_int, C.c_int, C.c_int, C.c_int, P, C.c_int, P]
lib.glm_values.argtypes = [P, P, C.c_int, C.c_int, C.c_int, P]
for name in ['glm_absorb', 'glm_attention', 'glm_values']:
    getattr(lib, name).restype = None
z = np.load(args.fixtures / 'mla_attention.npz')
# Torch k_b [heads,qk,latent] must transpose to GGUF [heads,latent,qk].
kb = np.ascontiguousarray(z['w.k_b'].transpose(0, 2, 1))
vb = z['w.v_b']
heads, latent_dim, qk_dim = kb.shape
value_dim = vb.shape[1]
for case in ['dense', 'sparse']:
    q = z[f'{case}.q_nope'][0]
    latent = z[f'{case}.latent'][0]
    tokens = q.shape[0]
    absorbed = np.empty((tokens, heads, latent_dim), dtype='float32')
    context = np.empty_like(absorbed)
    out = np.empty((tokens, heads, value_dim), dtype='float32')
    for t in range(tokens):
        lib.glm_absorb(ptr(q[t]), ptr(kb), heads, qk_dim, latent_dim, ptr(absorbed[t]))
        # Derive exact selected raw IDs from independent HF's boolean mask.
        ids = np.flatnonzero(z[f'{case}.sel_mask'][0, t]).astype('int32')
        assert np.all(ids <= t), (case, t, ids)
        lib.glm_attention(ptr(absorbed[t]), ptr(latent), t+1, heads,
                           latent_dim, qk_dim, ptr(ids), len(ids), ptr(context[t]))
        lib.glm_values(ptr(context[t]), ptr(vb), heads, latent_dim, value_dim, ptr(out[t]))
    check(f'mla/{case}/absorb', absorbed, z[f'{case}.q_absorbed'][0].transpose(1, 0, 2))
    check(f'mla/{case}/context', context, z[f'{case}.ctx_latent'][0].transpose(1, 0, 2))
    check(f'mla/{case}/values', out, z[f'{case}.attn_out'][0])
    # Output projection is numpy here, not a test of a C++ projection kernel.
    y = out.reshape(tokens, -1) @ z['w.o_proj'].T
    check(f'mla/{case}/projected-output', y, z[f'{case}.y'][0])
    if case == 'sparse':
        check('mla/sparse/vs-HF-cached-5+10', y, z['sparse.y_split_5_plus_10'][0])
print('ALL PASS (CPU op references only; no GPU/full-model/cache parity claim)')
